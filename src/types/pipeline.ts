/* ============================================================
   STAGE OUTPUT TYPES
   Each stage locks its output and passes it to the next.
   ============================================================ */

/**
 * PROSPECTING OUTPUT
 * Generated by the Prospecting tab when user locks an image.
 * Carries the concept art + all analysis data for Smelting.
 */
/** A LoRA applied to a generation: filename stem + weight. */
export interface LoraSelection {
  file:   string;   // LoRA id/stem (matches GET /api/loras `id`)
  weight: number;
}

export interface ProspectingOutput {
  /* Core image data */
  imagePath: string;           // original generated RGB image
  rgbaPath:  string | null;    // rembg'd RGBA — set by backend (Phase 5)
  svgPath:   string | null;    // vtracer SVG file path — set by backend (Phase 5)
  svgData:   string | null;    // inline SVG content for overlay / conditioning

  /* Pipeline context */
  prompt:    string;
  negPrompt: string;
  seed:      number;
  assetType: AssetType | null;
  artStyle:  ArtStyle  | null;

  /* Auto-selected by rules engine (set by backend in Phase 4) */
  lightingPreset:      string | null;
  reconstructionPath:  ReconstructionPath | null;

  /* Job tracking — used by Smelting to resolve file paths on the backend */
  prospectJobId:      string | null;   // backend job ID from the prospect run
  lockedImageIndex:   number;           // which image from the batch was locked

  /* LoRAs used for this generation — reused by the Pose page for style match */
  loras?: LoraSelection[];
}

/**
 * SMELTING OUTPUT
 * Generated by the Smelting tab when all views are approved + locked.
 * The full 3D data package — feeds directly into the Forge mesh pipeline.
 */
export interface SmeltingOutput {
  /* RGB views — one per angle */
  views: Record<ViewAngle, string>;          // angle → image URL

  /* Depth maps — generated alongside RGB (future phase) */
  depthMaps: Record<ViewAngle, string | null>;

  /* Silhouette masks — rembg RGBA per view */
  masks: Record<ViewAngle, string | null>;

  /* Single backend job ID */
  smeltJobId: string | null;

  /* Which pipeline generated these views */
  smeltMode: SmeltMode;

  /* SPRITE mode: the pose preset names generated (folder keys under smelt/) */
  poses?: string[];

  /* Generation settings used */
  prompt: string;

  /* Carried forward from Prospecting */
  prospectingData: ProspectingOutput | null;
}

/**
 * FORGE OUTPUT
 * Final result after mesh pipeline completes.
 * Points to the exported files + metadata.
 */
export interface ForgeOutput {
  meshPath:    string;                  // path to primary export (GLB/FBX/OBJ)
  lodPaths:    Record<string, string>;  // LOD0 → LOD3 paths
  texturePaths: {
    albedo:    string | null;
    normal:    string | null;
    roughness: string | null;
  };
  exportFormat:  ExportFormat;
  polyCount:     number;
  projectFolder: string;               // project folder root path
  completedAt:   string;               // ISO timestamp
}

