/* ============================================================
   SSE EVENT TYPES
   Events streamed from backend → frontend during long jobs.
   ============================================================ */
export type SSEEventType =
  | "progress"      // step progress update
  | "step_active"   // a pipeline step started
  | "step_done"     // a pipeline step completed
  | "image_ready"   // prospecting: single image downloaded + ready
  | "svg_ready"     // prospecting: SVG analysis complete
  | "view_ready"    // smelting: single view image ready
  | "mesh_ready"    // forge: mesh export available
  | "log"           // informational log message
  | "done"          // entire job completed
  | "error";        // entire job failed with error code

export interface SSEEvent {
  type:       SSEEventType;
  job_id?:    string;
  step_id?:   string;          // step id (e.g. "build", "decimate")
  message?:   string;          // human-readable status
  description?: string;        // step description
  output?:    string;          // step output (step_done)
  progress?:  number;          // 0.0 – 1.0
  pct?:       number;          // percent complete
  step?:      number;          // current step number
  total?:     number;          // total steps
  code?:      string;          // error code e.g. "ERROR_FORGE_BUILD"
  index?:     number;          // image index (prospecting)
  image_url?: string;          // image URL
  rgba_url?:  string | null;   // RGBA image URL
  raw_path?:  string | null;   // raw file path
  mesh_url?:  string | null;   // mesh URL (forge)
  out_dir?:   string | null;   // output directory (forge done)
  view_angle?: string;         // view angle (smelting)
  data?:      unknown;         // step-specific payload
}
